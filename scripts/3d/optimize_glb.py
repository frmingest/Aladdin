"""Step 3: shrink the raw models for the browser and register them with the game.

For each art-masters/3d/models/<slot>.glb: glTF-Transform (via npx) welds, simplifies, compresses
geometry with meshopt and textures to WebP at most --texture-size px, writing
frontend/src/assets/models/<slot>.glb (committed; budget below). Then it regenerates
frontend/src/game3d/models3d.ts, the list of slots that have a model. A slot without a model keeps
its shape figure, so you can add models one at a time.

  python scripts/3d/optimize_glb.py                 # all
  python scripts/3d/optimize_glb.py --only hero --texture-size 1024
Needs Node (npx). The first run downloads @gltf-transform/cli.
Budget: 1.5 MB per model (a warning above that); the whole game3d first load stays under 15 MB.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "art-masters" / "3d" / "models"
DST = ROOT / "frontend" / "src" / "assets" / "models"
TS_OUT = ROOT / "frontend" / "src" / "game3d" / "models3d.ts"
SLOTS = ["hero", "oracle", "partner", "fountain", "lamp", "board", "perch"]
BUDGET = 1_500_000


def write_manifest() -> list[str]:
    have = [s for s in SLOTS if (DST / f"{s}.glb").exists()]
    lines = [
        "// Generated by scripts/3d/optimize_glb.py - do not edit by hand.",
        '// Slots that have a real model. A slot not listed keeps its shape figure (Figures.tsx, PropModels.tsx).',
        'import type { ModelId } from "./modelFit";',
    ]
    lines += [f'import {s} from "../assets/models/{s}.glb?url";' for s in have]
    body = ", ".join(have)
    lines += ["", f"export const MODELS3D: Partial<Record<ModelId, string>> = {{ {body} }};".replace("{  }", "{}"), ""]
    TS_OUT.write_text("\n".join(lines), encoding="utf-8")
    return have


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", help="comma separated slots")
    ap.add_argument("--texture-size", type=int, default=1024)
    args = ap.parse_args()
    npx = shutil.which("npx") or shutil.which("npx.cmd")
    if not npx:
        raise SystemExit("npx not found: install Node.js first.")
    DST.mkdir(parents=True, exist_ok=True)
    only = set(args.only.split(",")) if args.only else None
    for glb in sorted(SRC.glob("*.glb")):
        slot = glb.stem
        if slot not in SLOTS or (only and slot not in only):
            continue
        out = DST / f"{slot}.glb"
        cmd = [npx, "--yes", "@gltf-transform/cli", "optimize", str(glb), str(out),
               "--compress", "meshopt", "--texture-compress", "webp", "--texture-size", str(args.texture_size)]
        print(f"{slot}: optimising")
        done = subprocess.run(cmd, capture_output=True, text=True)
        if done.returncode != 0:
            print(done.stdout[-500:], done.stderr[-500:], file=sys.stderr)
            return 1
        size = out.stat().st_size
        flag = "  OVER BUDGET: lower --texture-size or simplify in Modly" if size > BUDGET else ""
        print(f"{slot}: {glb.stat().st_size / 1e6:.1f} MB -> {size / 1e6:.2f} MB{flag}")
    have = write_manifest()
    print(f"models registered: {', '.join(have) or 'none'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
