"""Pack the 3D courtyard backdrop picture (offline dev tool, not run in CI).

Masters live OUTSIDE the shipped tree in art-masters/game3d/<id>.png (gitignored).
For each id below: key the white background out (same key as scripts/art/pack.py),
crop to the object, shrink to max_side, write frontend/src/assets/game3d/<id>.webp,
and write frontend/src/game3d/artManifest3d.ts (id -> file and picture size, so the
scene can keep the true aspect ratio). The backdrop is an opaque panorama, not keyed.

The people and props are solid models built from shapes in code (Figures.tsx, PropModels.tsx),
coloured after the Stitch pictures; only the backdrop is a picture. Stitch folder it came from
(2026-10-30, Faiz's "das" folder):
  backdrop  modify_and_re_render_the_scenic_mountain_and_lake_backdrop_...

Needs: pip install pillow numpy scipy
Usage: python scripts/art/pack_game3d.py [--masters art-masters/game3d]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
from pack import key_white  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "frontend" / "src" / "assets" / "game3d"
TS_OUT = ROOT / "frontend" / "src" / "game3d" / "artManifest3d.ts"

# id -> (key, max_side, quality)
OBJECTS: dict[str, tuple[str, int, int]] = {
    "backdrop": ("none", 1024, 76),
}




def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--masters", type=Path, default=ROOT / "art-masters" / "game3d")
    args = ap.parse_args()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for oid, (key, max_side, quality) in OBJECTS.items():
        src = args.masters / f"{oid}.png"
        if not src.exists():
            print(f"missing master: {src}", file=sys.stderr)
            return 1
        img = Image.open(src).convert("RGB")
        if key == "white":
            img = key_white(img)
            bbox = img.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
            if bbox:
                img = img.crop(bbox)
        img.thumbnail((max_side, max_side), Image.LANCZOS)
        out = OUT_DIR / f"{oid}.webp"
        img.save(out, "WEBP", quality=quality, method=6)
        rows.append((oid, img.width, img.height, out.stat().st_size))
        print(f"{oid:9s} {img.width}x{img.height} {out.stat().st_size / 1024:.0f} KB")
    lines = [
        "// Generated by scripts/art/pack_game3d.py - do not edit by hand.",
        '// Picture size is the packed (cropped) size, so a billboard keeps its true aspect ratio.',
    ]
    for oid, *_ in rows:
        lines.append(f'import {oid} from "../assets/game3d/{oid}.webp";')
    lines += ["", "export interface Art3d {", "  url: string;", "  width: number;", "  height: number;", "}", "",
              "export const ART3D = {"]
    for oid, w, h, _ in rows:
        lines.append(f"  {oid}: {{ url: {oid}, width: {w}, height: {h} }},")
    lines += ["} as const satisfies Record<string, Art3d>;", "", "export type Art3dId = keyof typeof ART3D;", ""]
    TS_OUT.write_text("\n".join(lines), encoding="utf-8")
    total = sum(r[3] for r in rows)
    print(f"total {total / 1024:.0f} KB; wrote {TS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
